import { nonUserMessageOrigin } from "@t3tools/client-runtime/user-message";
import { parseThreadLinkHref } from "@t3tools/shared/threadLinks";
import { isAttachmentOnlyBootstrapPrompt } from "@t3tools/shared/composerContextReferences";
import type { ThreadUserTurn } from "@t3tools/contracts";
import type { Nodes } from "mdast";
import remarkGfm from "remark-gfm";
import remarkParse from "remark-parse";
import { unified } from "unified";

import type { MessagesTimelineRow } from "./MessagesTimeline.logic";

export interface TimelineMinimapItem {
  readonly id: string;
  /** -1 for a turn outside the loaded rows; selecting it reveals the message. */
  readonly rowIndex: number;
  readonly userText: string | null;
  readonly assistantText: string | null;
  readonly branchOrigin?: boolean | undefined;
  readonly followUp?: boolean | undefined;
}

export function deriveTimelineMinimapItems(
  rows: ReadonlyArray<MessagesTimelineRow>,
): TimelineMinimapItem[] {
  const items: TimelineMinimapItem[] = [];
  for (let index = 0; index < rows.length; index += 1) {
    const row = rows[index];
    if (
      row?.kind !== "message" ||
      row.message.role !== "user" ||
      (row.message.createdBy !== undefined && row.message.createdBy !== "user") ||
      nonUserMessageOrigin(row.message) !== null
    ) {
      continue;
    }

    items.push({
      id: row.id,
      rowIndex: index,
      userText: isAttachmentOnlyBootstrapPrompt(row.message.text) ? "" : row.message.text,
      assistantText: resolveFinalAssistantTextForTurn(rows, index),
    });
  }
  return items;
}

/**
 * Adds the server's own turns older than the loaded window above it. A turn the server knows that
 * the rows do not yet hold is newer than the window, so it waits for its row.
 */
export function mergeUnloadedUserTurns(
  loaded: ReadonlyArray<TimelineMinimapItem>,
  turns: ReadonlyArray<ThreadUserTurn> | undefined,
): ReadonlyArray<TimelineMinimapItem> {
  if (!turns?.length) return loaded;
  const loadedIds = new Set(loaded.map((item) => item.id));
  const firstLoaded = turns.findIndex((turn) => loadedIds.has(turn.messageId));
  const older = firstLoaded === -1 ? turns : turns.slice(0, firstLoaded);
  if (older.length === 0) return loaded;
  return [
    ...older.map((turn) => ({
      id: turn.messageId,
      rowIndex: -1,
      userText: isAttachmentOnlyBootstrapPrompt(turn.text) ? "" : turn.text,
      assistantText: turn.replyText,
    })),
    ...loaded,
  ];
}

function resolveFinalAssistantTextForTurn(
  rows: ReadonlyArray<MessagesTimelineRow>,
  userRowIndex: number,
) {
  let finalAssistantText: string | null = null;
  for (let index = userRowIndex + 1; index < rows.length; index += 1) {
    const row = rows[index];
    if (row?.kind !== "message") {
      continue;
    }
    if (row.message.role === "user") {
      break;
    }
    if (row.message.role === "assistant") {
      finalAssistantText = row.message.text ?? null;
    }
  }
  return finalAssistantText;
}

const markdownPreviewParser = unified().use(remarkParse).use(remarkGfm).freeze();

const INLINE_PARENT_TYPES = new Set<Nodes["type"]>([
  "paragraph",
  "heading",
  "tableCell",
  "emphasis",
  "strong",
  "delete",
  "link",
  "linkReference",
]);

function markdownNodeText(node: Nodes): string {
  if (node.type === "html") {
    return node.value
      .replace(/<!--[\s\S]*?(?:-->|$)/g, "")
      .replace(/<\/?([a-z][\w-]*)(?:[^"'<>]|"[^"]*"|'[^']*')*>/gi, (_, tag: string) =>
        /^(?:address|article|aside|blockquote|br|dd|details|div|dl|dt|figcaption|figure|footer|h[1-6]|header|hr|li|main|nav|ol|p|pre|section|summary|table|tbody|td|th|thead|tr|ul)$/i.test(
          tag,
        )
          ? " "
          : "",
      );
  }
  if (node.type === "break") return " ";
  if ("value" in node) return node.value;
  if (node.type === "image" || node.type === "imageReference") return node.alt ?? "";
  if (!("children" in node)) return "";
  const separator = INLINE_PARENT_TYPES.has(node.type) ? "" : " ";
  const text = node.children.map(markdownNodeText).join(separator);
  // A thread autolink's only text is its URL.
  return node.type === "link" && parseThreadLinkHref(text) !== null ? "a thread" : text;
}

/** Markdown as one line of the text it renders, without markup or link targets. */
export function markdownPlainText(markdown: string): string {
  return markdownNodeText(markdownPreviewParser.parse(markdown)).replace(/\s+/g, " ").trim();
}

function compactMinimapPreview(text: string | null | undefined) {
  const compact = text?.replace(/\s+/g, " ").trim() ?? "";
  return compact.length > 0 ? compact : null;
}

export function resolveTimelineMinimapPreview(
  item: TimelineMinimapItem | null,
): TimelineMinimapItem | null {
  return item === null
    ? null
    : {
        ...item,
        userText: compactMinimapPreview(item.userText),
        // The tooltip shows three lines; bound parsing work while long responses stream.
        assistantText: compactMinimapPreview(
          item.assistantText === null
            ? null
            : markdownNodeText(markdownPreviewParser.parse(item.assistantText.slice(0, 1_500))),
        ),
      };
}
