// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - a one-shot maintenance script over git and the file system.
// Rebuilds the upstream contracts snapshot that apps/server/src/upstreamClientCompat.test.ts
// decodes the fork's wire payloads against: upstream's packages/contracts, bundled from a git ref
// with Effect external for the pinned test and bundled for a probe of another revision.
//
//   vp run upstream-contracts:refresh          from upstream/main (git fetch upstream first)
//   vp run upstream-contracts:refresh <ref>    from another ref
// UPSTREAM_SNAPSHOT=<path> writes a self-contained probe for the test to read with the same variable.
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeModule from "node:module";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

import { build } from "esbuild";

const root = NodePath.resolve(import.meta.dirname, "..");
const ref = process.argv[2] ?? "upstream/main";
const probe = process.env.UPSTREAM_SNAPSHOT;
const outfile = NodePath.resolve(
  probe ?? NodePath.join(root, "apps/server/src/upstreamClientCompat.snapshot.js"),
);
const git = (...args: Array<string>) =>
  NodeChildProcess.execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();

const sha = git("rev-parse", "--verify", `${ref}^{commit}`);
const date = git("show", "-s", "--format=%cs", sha);
const temp = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "t3-upstream-contracts-"));
try {
  const archive = NodePath.join(temp, "contracts.tar");
  const inputs = [
    "package.json",
    "pnpm-lock.yaml",
    "pnpm-workspace.yaml",
    ".pnpmfile.cjs",
    "patches",
    "packages/contracts",
    "tsconfig.base.json",
    "tsconfig.effect.json",
  ];
  git("archive", "--format=tar", "-o", archive, sha, ...inputs);
  NodeChildProcess.execFileSync("tar", ["-xf", archive, "-C", temp]);
  NodeChildProcess.execFileSync(
    "pnpm",
    [
      "--filter",
      "@t3tools/contracts",
      "install",
      "--prod",
      "--frozen-lockfile",
      "--ignore-scripts",
    ],
    { cwd: temp, stdio: "inherit" },
  );
  const contracts = NodePath.join(temp, "packages/contracts");
  const runtime = (dir: string) =>
    NodeModule.createRequire(NodePath.join(dir, "package.json"))("effect/package.json").version;
  const upstreamEffect = runtime(contracts);
  if (!probe && upstreamEffect !== runtime(import.meta.dirname)) {
    throw new Error(
      `Cannot refresh the pinned snapshot with Effect ${upstreamEffect}. Set UPSTREAM_SNAPSHOT to run a probe.`,
    );
  }
  const entry = NodePath.join(contracts, "entry.ts");
  NodeFS.writeFileSync(
    entry,
    [
      'export { WsRpcGroup } from "./src/rpc.ts";',
      'export { ExecutionEnvironmentDescriptor } from "./src/environment.ts";',
      'export { EnvironmentHttpApi } from "./src/environmentHttp.ts";',
      ...(probe
        ? [
            `
import { WsRpcGroup } from "./src/rpc.ts";
import * as RpcSchema from "effect/rpc/RpcSchema";
import * as Schema from "effect/Schema";

// Both the schema and its operations must come from upstream's Effect.
export function rpcWire(tag, kind, value) {
  const rpc = WsRpcGroup.requests.get(tag);
  if (!rpc) throw new Error(\`Upstream does not serve \${tag}\`);
  const stream = RpcSchema.isStreamSchema(rpc.successSchema) ? rpc.successSchema : null;
  const schema = kind === "request" ? rpc.payloadSchema
    : kind === "success" ? stream?.success ?? rpc.successSchema
    : stream?.error ?? rpc.errorSchema;
  const codec = Schema.toCodecJson(schema);
  return kind === "request"
    ? JSON.parse(JSON.stringify(Schema.encodeUnknownSync(codec)(value)))
    : Schema.decodeUnknownSync(codec)(value);
}
`,
          ]
        : []),
    ].join("\n"),
  );
  await build({
    entryPoints: [entry],
    // Module comments then name upstream paths, not the temporary directory.
    absWorkingDir: temp,
    outfile,
    bundle: true,
    format: "esm",
    platform: probe ? "node" : "neutral",
    external: probe ? [] : ["effect", "effect/*"],
    legalComments: "none",
    banner: {
      js: `// Generated by scripts/refresh-upstream-contracts.ts from ${ref === sha ? sha : `${ref} ${sha}`} (${date}). Do not edit.`,
    },
    logLevel: "warning",
  });
  console.log(`Built upstream contracts from ${sha} (${date}) with Effect ${upstreamEffect}.`);
} finally {
  NodeFS.rmSync(temp, { recursive: true });
}
